import { test, expect, type Page } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

const screenshots = resolve(process.cwd(), '../../docs/screenshots/modules')
mkdirSync(screenshots, { recursive: true })

async function login(page: Page, role: string) {
  await page.context().clearCookies()
  await page.goto('/login')
  await page.getByLabel('Tên đăng nhập', { exact: true }).fill('e2e-' + role)
  await page.getByLabel('Mật khẩu', { exact: true }).fill('e2e-only-password-29')
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login$/)
}

test('catalog and partner forms persist records across reload', async ({ page }) => {
  await login(page, 'admin')
  await page.goto('/admin/partners')
  await page.getByLabel('Tên đối tác', { exact: true }).fill('Nhà cung cấp E2E mới')
  const partnerResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/partners') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Lưu danh mục', exact: true }).click()
  const partner = await (await partnerResponse).json()
  await expect(page.getByRole('cell', { name: 'Nhà cung cấp E2E mới', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('cell', { name: 'Nhà cung cấp E2E mới', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'SKU & đơn vị tính', exact: true }).click()
  await page.getByLabel('Mã SKU', { exact: true }).fill('E2E-NEW')
  await page.getByLabel('Tên hàng', { exact: true }).fill('Hàng mới E2E')
  await page.getByLabel('Đơn vị cơ sở', { exact: true }).fill('hộp')
  await page.getByLabel('Chủ hàng', { exact: true }).selectOption('e2e-owner')
  const skuResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/skus') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Lưu danh mục', exact: true }).click()
  const sku = await (await skuResponse).json()
  await expect(page.getByRole('cell', { name: 'E2E-NEW', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Quan hệ cung ứng', exact: true }).click()
  await page.getByLabel('Chủ hàng', { exact: true }).selectOption('e2e-owner')
  await page.getByLabel('Nhà cung cấp', { exact: true }).selectOption(partner.id)
  await page.getByLabel('SKU được cung ứng', { exact: true }).selectOption(sku.id)
  await page.getByRole('button', { name: 'Lưu danh mục', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Nhà cung cấp E2E mới', exact: true })).toBeVisible()
  await page.screenshot({ path: resolve(screenshots, 'catalog.png'), fullPage: true })
})

