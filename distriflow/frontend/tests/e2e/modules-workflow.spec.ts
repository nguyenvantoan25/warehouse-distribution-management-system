test('supplier, warehouse, retailer and shipper complete one real workflow', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await login(page, 'supplier')
  await page.getByRole('button', { name: 'Tạo yêu cầu nhập', exact: true }).click()
  const editor = page.getByRole('dialog')
  await editor.getByLabel('Chủ hàng', { exact: true }).selectOption('e2e-owner')
  await editor.getByLabel('SKU', { exact: true }).selectOption('e2e-sku')
  await editor.getByLabel('Số lượng', { exact: true }).fill('100')
  const inboundResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/inbound-requests') && r.request().method() === 'POST')
  await editor.getByRole('button', { name: 'Gửi yêu cầu', exact: true }).click()
  const inbound = await (await inboundResponse).json()
  await expect(editor).not.toBeVisible()
  await expect(page.getByRole('button', { name: inbound.code, exact: true })).toBeVisible()
  await login(page, 'admin')
  await page.goto('/admin/inbounds')
  await page.getByRole('button', { name: inbound.code, exact: true }).click()
  await page.getByRole('button', { name: 'Duyệt nhập', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Ghi nhận kiểm nhận', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Ghi nhận kiểm nhận', exact: true }).click()
  await page.getByLabel('Vị trí lưu kho', { exact: true }).selectOption('e2e-location')
  await page.getByRole('button', { name: 'Xác nhận vị trí & tăng tồn', exact: true }).click()
  await expect(page.locator('.module-detail').getByText('Đã nhập kho', { exact: true })).toBeVisible()
  await page.screenshot({ path: resolve(screenshots, 'inbound.png'), fullPage: true })
  await login(page, 'retailer')
  await page.getByRole('button', { name: 'Tạo yêu cầu xuất', exact: true }).click()
  await editor.getByLabel('SKU', { exact: true }).selectOption('e2e-sku')
  await editor.getByLabel('Số lượng', { exact: true }).fill('25')
  const outboundResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/outbound-requests') && r.request().method() === 'POST')
  await editor.getByRole('button', { name: 'Gửi yêu cầu', exact: true }).click()
  const outbound = await (await outboundResponse).json()
  await expect(editor).not.toBeVisible()
  await login(page, 'admin')
  await page.goto('/admin/outbounds')
  await page.getByRole('button', { name: outbound.code, exact: true }).click()
  await page.getByRole('button', { name: 'Duyệt & giữ hàng', exact: true }).click()
  await page.getByRole('button', { name: 'Xác nhận soạn xong', exact: true }).click()
  await page.getByLabel('Số kiện đóng gói', { exact: true }).fill('3')
  await page.getByRole('button', { name: 'Đóng kiện & tạo nhiệm vụ', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Xem phiếu bàn giao', exact: true })).toBeVisible()
  await page.screenshot({ path: resolve(screenshots, 'outbound.png'), fullPage: true })
  await page.getByRole('link', { name: 'Xem phiếu bàn giao', exact: true }).click()
  const taskId = new URL(page.url()).pathname.split('/').pop()!
  const task = await (await page.request.get('/api/v1/pickup-tasks/' + taskId)).json()
  await page.goto('/admin/dispatch')
  await page.getByRole('checkbox', { name: 'Chọn ' + task.code, exact: true }).check()
  await page.getByLabel(/Shipper nhận hàng/).selectOption('e2e-shipper')
  await page.getByRole('button', { name: 'Xác nhận phân bổ', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Đã ghi nhận 1 phiếu')
  await login(page, 'shipper')
  await page.getByRole('button', { name: 'Nhận nhiệm vụ', exact: true }).click()
  await page.getByRole('button', { name: 'Tôi đã đến kho', exact: true }).click()
  for (const code of task.packages) {
    await page.getByLabel('Mã kiện', { exact: true }).fill(code)
    await page.getByRole('button', { name: 'Đối chiếu kiện', exact: true }).click()
    await expect(page.getByLabel('Mã kiện', { exact: true })).toHaveValue('')
  }
  await page.getByRole('button', { name: 'Xác nhận nhận hàng', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Đang chờ kho xác nhận')
  await login(page, 'admin')
  await page.goto('/admin/handovers/' + taskId)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Xác nhận tại kho', exact: true }).click()
  await expect(page.getByText('Đã hoàn tất bàn giao và ghi nhận xuất kho.', { exact: true })).toBeVisible()
  const receipt = await (await page.request.get('/api/v1/pickup-tasks/' + taskId + '/receipt')).json()
  expect(receipt.stockIssues.reduce((sum: number, line: { quantity: number }) => sum + line.quantity, 0)).toBe(25)
  const downloadReady = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Tải biên nhận JSON', exact: true }).click()
  expect((await downloadReady).suggestedFilename()).toBe(`bien-nhan-${task.code}.json`)
  await page.goto('/admin/inventory')
  const row = page.locator('tbody tr').filter({ hasText: 'E2E-SKU' })
  await expect(row.getByRole('cell', { name: '75', exact: true })).toHaveCount(2)
  await page.screenshot({ path: resolve(screenshots, 'inventory.png'), fullPage: true })
  await login(page, 'supplier')
  await page.goto('/admin/inventory')
  await expect(page.getByRole('heading', { name: 'Không có quyền truy cập', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
