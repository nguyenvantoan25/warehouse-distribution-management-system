  await page.getByLabel('Mã SKU', { exact: true }).fill('E2E-DEFAULT-THUNG')
  await page.getByLabel('Tên hàng', { exact: true }).fill('Sản phẩm đơn vị mặc định kiểm thử')
  await page.getByLabel('Chủ hàng', { exact: true }).selectOption('e2e-owner')
  const saved = page.waitForResponse(r => r.url().endsWith('/api/v1/skus') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Lưu danh mục', exact: true }).click()
