  const ownerIds = partners.filter((p: { kind: string; active: boolean }) => p.kind === 'RETAILER' && p.active)
    .map((p: { id: string }) => p.id).sort()
  const options = await page.getByLabel('Chủ hàng', { exact: true }).locator('option').evaluateAll(options =>
    options.map(option => (option as HTMLOptionElement).value).filter(Boolean).sort())
