async function login(page: Page, role: string) {
  await page.context().clearCookies()
  await page.goto('/login')
  await page.getByLabel('Tên đăng nhập', { exact: true }).fill('e2e-' + role)
  await page.getByLabel('Mật khẩu', { exact: true }).fill('e2e-only-password-29')
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login$/)
}

for (const scenario of [
  { role: 'admin', home: '/admin/dashboard', denied: '/supplier/inbounds', deniedApi: '/api/v1/auth/shipper-login' },
  { role: 'dispatch', home: '/admin/dashboard', denied: '/admin/catalog', deniedApi: '/api/v1/accounts' },
  { role: 'supplier', home: '/supplier/inbounds', denied: '/retailer/outbounds', deniedApi: '/api/v1/outbound-requests' },
  { role: 'retailer', home: '/retailer/outbounds', denied: '/supplier/inbounds', deniedApi: '/api/v1/inbound-requests' },
  { role: 'shipper', home: '/shipper/tasks', denied: '/admin/dashboard', deniedApi: '/api/v1/inventory/balances' },
]) {
  test(`${scenario.role} opens its own portal and cannot cross boundaries`, async ({ page }) => {
    await login(page, scenario.role)
    await expect(page).toHaveURL(new RegExp(scenario.home + '$'))
    await page.reload()
    await expect(page).toHaveURL(new RegExp(scenario.home + '$'))
    if (['supplier', 'retailer'].includes(scenario.role)) {
      await page.setViewportSize({ width: 390, height: 844 })
      await page.getByRole('button', { name: 'Mở menu', exact: true }).click()
      const navigation = page.getByRole('navigation')
      await expect(navigation).toBeVisible()
      await expect(navigation).toHaveCSS('position', 'static')
      await expect(page.locator('.ops-sidebar')).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
      await expect(navigation.getByRole('link')).toHaveCount(scenario.role === 'supplier' ? 1 : 2)
      await page.screenshot({ path: `test-results/${scenario.role}-portal-mobile.png`, fullPage: true })
      await page.getByRole('button', { name: 'Đóng menu', exact: true }).click()
      await expect(page.getByRole('button', { name: 'Đóng menu', exact: true })).toBeHidden()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    }
    await page.goto(scenario.denied)
    await expect(page).toHaveURL(/\/forbidden$/)
    if (scenario.role !== 'admin') {
      expect((await page.request.get(scenario.deniedApi)).status()).toBe(403)
    }
    await page.goto('/')
    await expect(page).toHaveURL(new RegExp(scenario.home + '$'))
  })
}

